#!/bin/sh
# Deterministic Emberstage portal/backend map generator.
# Usage: sh scripts/gen-maps.sh [output-dir]   (default: docs)
# No timestamps, no absolute paths, sorted output. Run from the repo root.
set -eu

OUT=${1:-docs}
mkdir -p "$OUT"

emit_code_map() {
  cat <<'EOF'
# Emberstage portal and backend code map

Generated by `scripts/gen-maps.sh`. Do not edit by hand. Run
`sh scripts/check-maps.sh` to detect drift, or `sh scripts/gen-maps.sh` to
regenerate the committed baseline.

## Server modules

EOF
  find server/src -maxdepth 1 -type f -name '*.js' -print 2>/dev/null | LC_ALL=C sort \
    | while IFS= read -r f; do printf -- '- `%s`\n' "$f"; done
  printf '\n'

  cat <<'EOF'
## HTTP route table

Extracted from `addRoute(method, path, ...)` calls. Auth roles and authKind are
security-relevant; inspect the source when adding a route. This table does not
prove a route is enabled in the deployed configuration.

EOF
  for f in $(find server/src -maxdepth 1 -type f -name '*.js' -print | LC_ALL=C sort); do
    routes=$(sed -n "s/^[[:space:]]*addRoute('\([A-Z]*\)', '\([^']*\)'.*/\1 \2/p" "$f")
    if [ -n "$routes" ]; then
      printf -- '### %s\n\n' "$f"
      printf '%s\n' "$routes" | LC_ALL=C sort | while IFS=' ' read -r method path; do
        printf -- '- `%s %s`\n' "$method" "$path"
      done
      printf '\n'
    fi
  done

  cat <<'EOF'
## Subsystems and boundaries

- `server/src/server.js`: request dispatch, auth, entitlements, safe status projection.
- `server/src/worker-manager.js`: ffmpeg child processes and relay fanout. Its ffmpeg
  environment is an explicit allowlist, not inherited process environment.
- `server/src/db.js`: SQLite schema, stream sessions and publish-capability storage.
- `server/src/nango-client.js`: provider OAuth client. Configuration may be disabled.
- `server/src/camera-rooms.js`: WebRTC camera signaling. May be disabled in deployment.
- `server/public/`: portal HTML/CSS/JS and the first-open loader assets.
- `deploy/nango/docker-compose.yml`: local Nango development stack only.

The portal is the account and destination control plane. Desk is an RTMP encoder
and does not hold provider tokens or the Nango secret.
EOF
}

emit_infra_map() {
  cat <<'EOF'
# Emberstage portal and backend infrastructure map

Generated by `scripts/gen-maps.sh`. Derived only from committed deploy files.
No live cloud API is called. Do not edit by hand. Run `sh scripts/check-maps.sh`
to detect drift.

## Personal AWS deploy assets

EOF
  find server/deploy/personal-aws -maxdepth 1 -type f -print 2>/dev/null | LC_ALL=C sort \
    | while IFS= read -r f; do printf -- '- `%s`\n' "$f"; done
  printf '\n'

  cat <<'EOF'
## systemd service

EOF
  grep -nE '^(User|Group|WorkingDirectory|EnvironmentFile|ExecStart|Restart|RestartSec)=' \
    server/deploy/personal-aws/emberstage.service 2>/dev/null \
    | sed 's/^/`/; s/:/`: /' || true
  printf '\n'

  cat <<'EOF'
## nginx listeners and proxy targets

EOF
  grep -nE 'listen[[:space:]]|server_name[[:space:]]|proxy_pass[[:space:]]|root[[:space:]]' \
    server/deploy/personal-aws/nginx.conf 2>/dev/null \
    | sed 's/^/`/; s/:/`: /' || true
  printf '\n'

  cat <<'EOF'
## Local stacks and backup

- `deploy/nango/docker-compose.yml`: local Nango development only.
- `server/deploy/personal-aws/backup.py` and the systemd timer: same-disk SQLite
  backup. This is not disaster recovery; restoring encrypted data also needs the
  runtime secret.
- Runtime secret: `/etc/emberstage/runtime.env`, root-only. It is never mapped
  or emitted by this generator.

## Deployment truth

The committed deploy scripts are the source of truth for the permanent host.
This map never describes a live resource as current. Live reachability, TLS,
ports and service state require a separate explicitly authorized read-only probe.
Features disabled in the shipped configuration are not proven by their presence
in this map.
EOF
}

emit_code_map > "$OUT/CODE_MAP.md"
emit_infra_map > "$OUT/INFRA_MAP.md"
